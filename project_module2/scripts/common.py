"""Shared paths and loaders for FAR-Trans (project_module2)."""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "FAR-Trans"
REPORTS = ROOT / "reports"
FIGS = REPORTS / "figures"

TABLES = {
    "transactions": ["timestamp"],
    "customer_information": ["timestamp", "lastQuestionnaireDate"],
    "asset_information": ["timestamp"],
    "close_prices": ["timestamp"],
    "limit_prices": ["minDate", "maxDate"],
    "markets": [],
}

# Provisional split (assumption, NOT official): paper protocol with delta t = 6 months,
# latest possible cut point so the test window ends at the last transaction date.
CUT = pd.Timestamp("2022-05-31")
TEST_END = pd.Timestamp("2022-11-30")

HEADER = "<!-- auto-generated by scripts/{name}; do not edit by hand -->\n\n"


def load(name: str) -> pd.DataFrame:
    df = pd.read_csv(DATA / f"{name}.csv", dtype={"ISIN": str, "customerID": str})
    for col in TABLES.get(name, []):
        df[col] = pd.to_datetime(df[col], errors="coerce")
    return df


def profile_asof(cust: pd.DataFrame, when: pd.Timestamp) -> pd.DataFrame:
    """Latest customer profile row with timestamp <= when (point-in-time, no look-ahead)."""
    past = cust[cust["timestamp"] <= when]
    return past.sort_values("timestamp").groupby("customerID").tail(1)


def md_table(df: pd.DataFrame) -> str:
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join(str(v).replace("|", "/") for v in row) + " |")
    return "\n".join(lines)


def write(name: str, script: str, text: str) -> None:
    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / name).write_text(HEADER.format(name=script) + text, encoding="utf-8")
    print("wrote", REPORTS / name)
