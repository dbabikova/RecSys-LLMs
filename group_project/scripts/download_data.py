"""Download and verify the FAR-Trans dataset, then write a data manifest.

Downloads (idempotently) the dataset archive and its README into ``data/raw/``,
extracts the archive, and writes ``reports/session1/data_manifest.md`` containing
the source URL, download date, size and SHA-256 of every file (archive, README
and each extracted file).

Usage::

    python scripts/download_data.py
"""

from __future__ import annotations

import hashlib
import sys
import urllib.request
import zipfile
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAW_DIR = ROOT / "data" / "raw"
REPORT_DIR = ROOT / "reports" / "session1"

ZIP_URL = "https://researchdata.gla.ac.uk/1658/1/FAR-Trans.zip"
README_URL = "https://researchdata.gla.ac.uk/1658/2/README.txt"

ZIP_NAME = "FAR-Trans.zip"
README_NAME = "README.txt"
EXTRACT_DIR_NAME = "FAR-Trans"

MANIFEST_NAME = "data_manifest.md"


def sha256_hex(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def download(url: str, dest: Path) -> bool:
    """Download ``url`` to ``dest`` unless it already exists.

    Returns True if a new file was downloaded, False if it was already present.
    """
    if dest.exists():
        print(f"skip (exists): {dest.name}")
        return False
    dest.parent.mkdir(parents=True, exist_ok=True)
    print(f"download: {url} -> {dest}")
    urllib.request.urlretrieve(url, dest)
    return True


def extract_zip(zip_path: Path, extract_dir: Path) -> None:
    if extract_dir.exists():
        print(f"skip (exists): {extract_dir.name}")
        return
    print(f"extract: {zip_path.name} -> {extract_dir}")
    with zipfile.ZipFile(zip_path) as archive:
        archive.extractall(extract_dir.parent)


def write_manifest(
    zip_path: Path,
    readme_path: Path,
    extract_dir: Path,
    downloaded_at: datetime,
) -> Path:
    files: list[tuple[str, str, int, str]] = []

    files.append((ZIP_NAME, ZIP_URL, zip_path.stat().st_size, sha256_hex(zip_path)))
    files.append(
        (README_NAME, README_URL, readme_path.stat().st_size, sha256_hex(readme_path))
    )
    for child in sorted(extract_dir.iterdir()):
        if child.is_file():
            rel = f"{EXTRACT_DIR_NAME}/{child.name}"
            files.append(
                (rel, f"extracted from {ZIP_URL}", child.stat().st_size, sha256_hex(child))
            )

    lines: list[str] = []
    lines.append("<!-- auto-generated by scripts/download_data.py — do not edit manually -->")
    lines.append("# Data manifest")
    lines.append("")
    lines.append(f"**Downloaded (UTC):** {downloaded_at.isoformat()}")
    lines.append("")
    lines.append("| File | Source | Size (bytes) | SHA-256 |")
    lines.append("|------|--------|-------------:|---------|")
    for name, source, size, digest in files:
        lines.append(f"| `{name}` | {source} | {size} | `{digest}` |")
    lines.append("")

    manifest = REPORT_DIR / MANIFEST_NAME
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    manifest.write_text("\n".join(lines), encoding="utf-8")
    return manifest


def main() -> int:
    RAW_DIR.mkdir(parents=True, exist_ok=True)

    zip_path = RAW_DIR / ZIP_NAME
    readme_path = RAW_DIR / README_NAME
    extract_dir = RAW_DIR / EXTRACT_DIR_NAME

    download(ZIP_URL, zip_path)
    download(README_URL, readme_path)
    extract_zip(zip_path, extract_dir)

    if not zip_path.exists() or not readme_path.exists():
        print("error: required files are missing after download", file=sys.stderr)
        return 1

    downloaded_at = datetime.now(timezone.utc)
    manifest = write_manifest(zip_path, readme_path, extract_dir, downloaded_at)
    print(f"wrote: {manifest.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
