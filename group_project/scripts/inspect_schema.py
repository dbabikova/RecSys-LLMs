"""Compute FAR-Trans schema statistics and write ``reports/session1/schema_stats.md``.

The generated file is the single source of truth for every number quoted in
``reports/session1/schema.md``. For each CSV file the script reports row/column
counts, dtypes, missing values (empty strings and the ``2000-01-01`` date
sentinel), unique counts and min/max dates; plus cross-file counters and
categorical distributions. Raw data rows are never printed to stdout.

Usage::

    python scripts/inspect_schema.py
"""

from __future__ import annotations

import sys
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW_DIR = ROOT / "data" / "raw" / "FAR-Trans"
REPORT_DIR = ROOT / "reports" / "session1"

STATS_NAME = "schema_stats.md"
SENTINEL_DATE = "2000-01-01"

DATE_COLUMNS = {"timestamp", "lastQuestionnaireDate", "minDate", "maxDate"}

CSV_FILES = [
    "customer_information.csv",
    "asset_information.csv",
    "markets.csv",
    "close_prices.csv",
    "limit_prices.csv",
    "transactions.csv",
]

# columns whose value-count distribution is required
DISTRIBUTIONS = {
    "customer_information.csv": ["customerType", "riskLevel", "investmentCapacity"],
    "asset_information.csv": ["assetCategory"],
    "transactions.csv": ["transactionType", "channel"],
}

UNIQUE_COUNTS = {
    "customer_information.csv": ["customerID"],
    "asset_information.csv": ["ISIN"],
    "close_prices.csv": ["ISIN"],
    "limit_prices.csv": ["ISIN"],
    "transactions.csv": ["customerID", "ISIN"],
}


def load(name: str) -> pd.DataFrame:
    return pd.read_csv(RAW_DIR / name, keep_default_na=False)


def fmt_date(series: pd.Series) -> str:
    dates = pd.to_datetime(series, errors="coerce").dropna()
    if dates.empty:
        return "—"
    return f"{dates.min().date()} … {dates.max().date()}"


def column_rows(df: pd.DataFrame) -> list[str]:
    rows: list[str] = []
    for col in df.columns:
        series = df[col]
        n = len(series)
        empty = int((series == "").sum())
        nan = int(series.isna().sum())
        unique = int(series.nunique(dropna=True))

        cells = [
            f"`{col}`",
            str(series.dtype),
            f"{n - empty - nan}",
            f"{empty}",
            f"{nan}",
            f"{unique}",
        ]

        if col in DATE_COLUMNS:
            sentinel = int((series == SENTINEL_DATE).sum())
            cells.append(f"{sentinel}")
            cells.append(fmt_date(series))
        else:
            cells.append("—")
            cells.append("—")

        rows.append("| " + " | ".join(cells) + " |")
    return rows


def main() -> int:
    if not RAW_DIR.exists():
        print(f"error: raw dir not found: {RAW_DIR}", file=sys.stderr)
        return 1

    frames = {name: load(name) for name in CSV_FILES}

    out: list[str] = []
    out.append("<!-- auto-generated by scripts/inspect_schema.py — do not edit manually -->")
    out.append("# Schema statistics")
    out.append("")
    out.append(f"**Generated (UTC):** {datetime.now(timezone.utc).isoformat()}")
    out.append("")
    out.append(f"**Sentinel date:** `{SENTINEL_DATE}` is treated as a missing-date placeholder.")
    out.append("")
    out.append("## Files")
    out.append("")
    out.append("| File | Rows (excl. header) | Columns |")
    out.append("|------|--------------------:|--------:|")
    for name in CSV_FILES:
        df = frames[name]
        out.append(f"| `{name}` | {len(df)} | {len(df.columns)} |")

    # questionnaires.csv is plain text, not CSV
    q_path = RAW_DIR / "questionnaires.csv"
    q_lines = q_path.read_text(encoding="utf-8").count("\n") + 1
    out.append(f"| `questionnaires.csv` (plain text) | {q_lines} lines | — |")
    out.append("")

    out.append("## Per-column details")
    out.append("")
    out.append("`non-empty` excludes empty strings and NaN; `sentinel` counts the")
    out.append(f"`{SENTINEL_DATE}` placeholder in date columns; `min … max` is the parsed")
    out.append("date range (including the sentinel where present).")
    out.append("")
    header = "| Column | dtype | non-empty | empty | NaN | unique | sentinel | min … max |"
    sep = "|--------|-------|----------:|------:|----:|-------:|---------:|-----------|"
    for name in CSV_FILES:
        out.append(f"### `{name}`")
        out.append("")
        out.append(header)
        out.append(sep)
        out.extend(column_rows(frames[name]))
        out.append("")

    out.append("## Summary counters")
    out.append("")
    out.append("### Unique identifiers")
    out.append("")
    out.append("| File | Column | Unique values |")
    out.append("|------|--------|--------------:|")
    for name, cols in UNIQUE_COUNTS.items():
        df = frames[name]
        for col in cols:
            out.append(f"| `{name}` | `{col}` | {int(df[col].nunique(dropna=True))} |")
    out.append("")

    out.append("### Categorical distributions")
    out.append("")
    for name, cols in DISTRIBUTIONS.items():
        df = frames[name]
        for col in cols:
            out.append(f"#### `{name}` → `{col}`")
            out.append("")
            out.append("| Value | Count |")
            out.append("|-------|------:|")
            counts = df[col].value_counts(dropna=False).sort_index()
            for value, count in counts.items():
                out.append(f"| `{value}` | {int(count)} |")
            out.append("")

    stats_path = REPORT_DIR / STATS_NAME
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    stats_path.write_text("\n".join(out), encoding="utf-8")

    print(f"wrote: {stats_path.relative_to(ROOT)} ({len(CSV_FILES)} CSV files + questionnaires)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
