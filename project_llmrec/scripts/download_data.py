"""Fetch FAR-Trans, verify its SHA-256, extract it and write a data manifest.

Usage:
    python scripts/download_data.py                    # download from researchdata.gla.ac.uk
    python scripts/download_data.py --zip PATH.zip     # use a local copy of FAR-Trans.zip

The archive is never re-downloaded if data/raw/FAR-Trans.zip already exists.
Output: reports/session1/data_manifest.md
"""
from __future__ import annotations

import argparse
import hashlib
import shutil
import sys
import urllib.request
import zipfile
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from llmrec.data import RAW_DIR, REPORTS_DIR, ZIP_SHA256, ZIP_URL  # noqa: E402


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--zip", type=Path, help="local copy of FAR-Trans.zip")
    args = ap.parse_args()

    RAW_DIR.mkdir(parents=True, exist_ok=True)
    zip_path = RAW_DIR / "FAR-Trans.zip"
    if zip_path.exists():
        how = "already present, not re-downloaded"
    elif args.zip:
        shutil.copyfile(args.zip, zip_path)
        how = f"copied from a local file ({args.zip.name})"
    else:
        print(f"downloading {ZIP_URL}")
        urllib.request.urlretrieve(ZIP_URL, zip_path)
        how = "downloaded"

    digest = sha256(zip_path)
    if digest != ZIP_SHA256:
        sys.exit(f"SHA-256 mismatch: got {digest}, expected {ZIP_SHA256}")

    with zipfile.ZipFile(zip_path) as z:
        z.extractall(RAW_DIR)
        members = sorted(n for n in z.namelist() if not n.endswith("/"))

    rows = [(zip_path.name, zip_path.stat().st_size, digest)]
    for m in members:
        p = RAW_DIR / m
        rows.append((m, p.stat().st_size, sha256(p)))

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    lines = [
        "<!-- auto-generated by scripts/download_data.py; do not edit by hand -->",
        "# Data manifest",
        "",
        f"- Source: {ZIP_URL} (University of Glasgow research data repository, CC BY 4.0)",
        f"- Archive: {how}; SHA-256 verified against the expected value.",
        f"- Manifest written (UTC): {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M')}",
        "",
        "| File | Size (bytes) | SHA-256 |",
        "|---|---:|---|",
    ]
    lines += [f"| `{n}` | {s} | `{h}` |" for n, s, h in rows]
    (REPORTS_DIR / "data_manifest.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"ok: {len(members)} files extracted, manifest written")


if __name__ == "__main__":
    main()
