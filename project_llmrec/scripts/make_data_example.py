"""One real FAR-Trans record plus field-level and dataset-level leakage checks.

Output: reports/session1/data_example.md (auto-generated).

Selection rule (deterministic, seed 42): a Buy transaction that
  * is not in January 2018 (an outlier month, see eda.md),
  * has a transactionID used by only one customer (no shared/joint record),
  * has a customer snapshot fully available on or before the transaction date
    (available_from = max(timestamp, lastQuestionnaireDate) <= date),
  * has an asset_information row dated on or before the transaction date.
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from llmrec.data import (  # noqa: E402
    REPORTS_DIR, SENTINEL_DATE, load_assets, load_customers, load_transactions, read_raw,
)

SEED = 42
SOURCE = "FAR-Trans (https://researchdata.gla.ac.uk/1658/), file"


def mask(cid: str) -> str:
    return cid[:6] + "…"


def pct(a: int, b: int) -> str:
    return f"{a} of {b} ({100 * a / b:.2f}%)"


def block(file: str, rid: str, fields: list[str], values: list[str], window: str) -> list[str]:
    return ["```", f"source:    {SOURCE} {file}", f"record id: {rid}",
            f"fields:    {', '.join(fields)}", f"values:    {', '.join(values)}",
            f"window:    {window}", "```"]


def main() -> None:
    tx_raw = read_raw("transactions.csv")
    cu_raw = read_raw("customer_information.csv")
    as_raw = read_raw("asset_information.csv")
    tx, cu, assets = load_transactions(), load_customers(), load_assets()

    # ---- pick the example -------------------------------------------------
    shared = tx.transactionID.duplicated(keep=False)
    buys = tx[(tx.transactionType == "Buy") & ~shared & (tx.timestamp >= "2018-02-01")]
    snap = cu.dropna(subset=["timestamp"])[["customerID", "available_from"]]
    ok_cust = buys.merge(snap, on="customerID")
    ok_cust = ok_cust[ok_cust.available_from <= ok_cust.timestamp].transactionID.unique()
    first_asset = assets.groupby("ISIN").timestamp.min()
    ok = buys[buys.transactionID.isin(ok_cust) & (buys.ISIN.map(first_asset) <= buys.timestamp)]
    ok = ok.sort_values("transactionID")
    i = np.random.default_rng(SEED).integers(len(ok))
    t = ok.iloc[i]
    t_raw = tx_raw.loc[t.name]
    date = t.timestamp

    c = cu[(cu.customerID == t.customerID) & cu.timestamp.notna() & (cu.available_from <= date)]
    c = c.sort_values("available_from").iloc[-1]
    c_raw = cu_raw.loc[c.name]
    n_snap = int((cu.customerID == t.customerID).sum())
    a = assets[(assets.ISIN == t.ISIN) & (assets.timestamp <= date)].sort_values("timestamp").iloc[-1]
    a_raw = as_raw.loc[a.name]

    tx_vals = [mask(v) if k == "customerID" else v for k, v in t_raw.items()]
    cu_vals = [mask(v) if k == "customerID" else v for k, v in c_raw.items()]
    d = date.date()

    L = ["<!-- auto-generated by scripts/make_data_example.py; do not edit by hand -->",
         "# One FAR-Trans record and leakage check (Session 1)", "",
         "> **Split status:** the official time cut, item scope and evaluated users are **pending**. "
         "Everything about the split below is **provisional**.", "",
         f"Selected deterministically (`numpy.random.default_rng({SEED})`, index {i} of {len(ok)} eligible "
         "Buy rows sorted by transactionID). Eligibility: not January 2018; transactionID used by one "
         "customer only; a customer snapshot and an asset row exist on or before the transaction date.", "",
         "Anonymisation: `customerID` (already a pseudonymous hash in the release) is truncated to 6 characters "
         "+ `…`. ISIN and asset names are public market identifiers and are kept. All other values are verbatim "
         "strings from the raw CSV.", "",
         "## The record (primary): one purchase", ""]
    L += block("transactions.csv", f"transactionID {t_raw.transactionID}", list(tx_raw.columns), tx_vals,
               f"transaction date {d}; position relative to the official cut: pending (provisional)")
    L += ["", "Context rows joined point-in-time (the latest rows dated on or before the transaction date):", ""]
    L += block("customer_information.csv", f"{mask(c_raw.customerID)} snapshot of {c_raw.timestamp} "
               f"({n_snap} snapshot(s) for this customer in total)", list(cu_raw.columns), cu_vals,
               f"snapshot timestamp {c_raw.timestamp}, questionnaire {c_raw.lastQuestionnaireDate}")
    L += [""]
    L += block("asset_information.csv", f"ISIN {a_raw.ISIN} version of {a_raw.timestamp}",
               list(as_raw.columns), [v if v else "(empty)" for v in a_raw.values], f"asset row timestamp {a_raw.timestamp}")

    # ---- field table -----------------------------------------------------
    L += ["", "## Field status and timestamps", "",
          "Prediction time = the **provisional cut** `T`, not the date of this transaction. "
          "A transaction row is an input only if its date is `< T`; rows with date `>= T` are labels "
          "(the future purchases scored by nDCG@10) and none of their fields may enter model inputs.", "",
          "| File | Field | Status | Timestamp that governs it | As history (date < T) | As target (date ≥ T) |",
          "|---|---|---|---|---|---|"]
    for f in tx_raw.columns:
        L.append(f"| transactions | `{f}` | observed | `transactions.timestamp` | usable | forbidden as input (label row) |")
    rl, ic = c_raw.riskLevel, c_raw.investmentCapacity
    for f in cu_raw.columns:
        v = c_raw[f]
        status = "observed"
        if v.startswith("Predicted_"):
            status = "predicted/estimated (bank algorithm)"
        elif v in ("Not_Available", "") or (f in ("timestamp", "lastQuestionnaireDate") and v == SENTINEL_DATE.strftime("%Y-%m-%d")):
            status = "missing"
        gov = "`max(timestamp, lastQuestionnaireDate)`" if f in ("riskLevel", "investmentCapacity") else "`customer_information.timestamp`"
        if f == "lastQuestionnaireDate":
            gov = "its own value"
        L.append(f"| customer_information | `{f}` | {status} | {gov} | usable if that date < T | not a label |")
    for f in as_raw.columns:
        status = "missing" if a_raw[f] == "" else "observed"
        L.append(f"| asset_information | `{f}` | {status} | `asset_information.timestamp` | usable if that date < T | not a label |")
    L += ["", f"In this example the customer fields are `riskLevel={rl}`, `investmentCapacity={ic}`. "
          "`limit_prices.profitability` is not part of the record and is excluded from all inputs (see below)."]

    # ---- dataset-level checks -------------------------------------------
    first_tx = tx.groupby("customerID").timestamp.min()
    cu2 = cu.assign(first_tx=cu.customerID.map(first_tx))
    both = cu.timestamp.notna() & cu.lastQuestionnaireDate.notna()
    q_after = both & (cu.lastQuestionnaireDate > cu.timestamp)
    after_first = cu2.timestamp.notna() & (cu2.timestamp > cu2.first_tx)
    has_ts = cu2[cu2.timestamp.notna() & (cu2.timestamp <= cu2.first_tx)].customerID.nunique()
    has_av = cu2[cu2.timestamp.notna() & (cu2.available_from <= cu2.first_tx)].customerID.nunique()
    n_c = cu.customerID.nunique()
    n = len(cu)
    pred_r = cu_raw.riskLevel.str.startswith("Predicted_").sum()
    pred_c = cu_raw.investmentCapacity.str.startswith("Predicted_").sum()
    na_r = (cu_raw.riskLevel == "Not_Available").sum()
    na_c = (cu_raw.investmentCapacity == "Not_Available").sum()
    sent_ts = (read_raw("customer_information.csv").timestamp == "2000-01-01").sum()
    sent_q = (read_raw("customer_information.csv").lastQuestionnaireDate == "2000-01-01").sum()

    b_all = tx[tx.transactionType == "Buy"]
    early = int((b_all.timestamp < b_all.ISIN.map(first_asset)).sum())
    lp = read_raw("limit_prices.csv")
    lp_late = int((pd.to_datetime(lp.maxDate) >= "2022-11-01").sum())
    shared_buys = int((shared & (tx.transactionType == "Buy")).sum())

    L += ["", "## Dataset-level leakage checks (computed)", "",
          "**Customer profiles (`customer_information.csv`, 32468 snapshots)**", "",
          f"- Snapshots with `lastQuestionnaireDate > timestamp` (both non-sentinel): {pct(int(q_after.sum()), int(both.sum()))}, "
          f"affecting {cu[q_after].customerID.nunique()} customers. Using `timestamp` alone would admit questionnaire "
          "answers from the future, so a snapshot is treated as available only from "
          "`available_from = max(timestamp, lastQuestionnaireDate)`.",
          f"- Sentinel `2000-01-01`: {sent_ts} `timestamp` values and {sent_q} `lastQuestionnaireDate` values (treated as unknown).",
          f"- Customers with more than one snapshot: {int((cu.customerID.value_counts() > 1).sum())} of {n_c}.",
          f"- Snapshots whose `timestamp` is after the customer's first transaction: {pct(int(after_first.sum()), n)}, "
          f"for {cu2[after_first].customerID.nunique()} customers.",
          f"- Customers with **no** snapshot dated on or before their first transaction: "
          f"{n_c - has_ts} by `timestamp`; {n_c - has_av} by `available_from`. For them, any profile feature at the "
          "time of their earliest purchases would come from the future.",
          f"- `riskLevel`: Predicted_* {pct(int(pred_r), n)}; Not_Available {pct(int(na_r), n)}.",
          f"- `investmentCapacity`: Predicted_* {pct(int(pred_c), n)}; Not_Available {pct(int(na_c), n)}.",
          "",
          "**Assets**", "",
          f"- ISINs with more than one row in `asset_information.csv`: {int((assets.ISIN.value_counts() > 1).sum())}. "
          "The row used must be the latest one dated before `T`.",
          f"- Buy rows dated before the earliest `asset_information` row of their ISIN: {pct(early, len(b_all))}"
          + (" (point-in-time asset metadata is missing for these purchases)." if early else
             ", so a point-in-time asset row exists for every purchase."),
          f"- `limit_prices.profitability` is the return between each asset's `minDate` and `maxDate`; "
          f"{lp_late} of {len(lp)} assets have `maxDate` in November 2022. It summarises the whole price series, "
          "so it is **excluded** from inputs. Price features must be computed from `close_prices` rows dated `< T`.",
          "",
          "**Transactions**", "",
          f"- Buy rows whose `transactionID` is shared with another customer (all other fields identical): "
          f"{pct(shared_buys, len(b_all))}. The same purchase therefore appears as a label for several users; "
          "how the official protocol treats these rows is pending.",
          "- Transaction rows dated `>= T` are labels only; no aggregate (popularity counts, co-occurrence, "
          "embeddings) may be computed from them.", ""]
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (REPORTS_DIR / "data_example.md").write_text("\n".join(L), encoding="utf-8")
    print("ok: reports/session1/data_example.md")


if __name__ == "__main__":
    main()
