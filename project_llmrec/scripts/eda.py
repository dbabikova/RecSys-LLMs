"""Exploratory analysis of FAR-Trans for the Session 1 study plan.

Outputs: reports/session1/eda.md, reports/session1/figures/*.png,
         reports/session1/tables/monthly_buys_by_category.csv
All numbers count Buy transactions only unless stated otherwise.
"""
from __future__ import annotations

import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from llmrec.data import (  # noqa: E402
    FIG_DIR, REPORTS_DIR, asset_category_map, load_customers, load_transactions, read_raw,
)

CUTS = ["2022-03-01", "2022-06-01", "2022-09-01"]
CATS = ["Stock", "MTF", "Bond"]


def pct(x: float) -> str:
    return f"{100 * x:.2f}%"


def buckets(s: pd.Series) -> str:
    n = len(s)
    parts = [("1", s == 1), ("2–4", s.between(2, 4)), ("5–9", s.between(5, 9)), ("10+", s >= 10)]
    return "; ".join(f"{k}: {int(m.sum())} ({pct(m.sum() / n)})" for k, m in parts)


def main() -> None:
    tx = load_transactions()
    cat = asset_category_map()
    tx["cat"] = tx.ISIN.map(cat)
    b = tx[tx.transactionType == "Buy"].sort_values(["timestamp", "transactionID"]).copy()
    end = tx.timestamp.max()
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    (REPORTS_DIR / "tables").mkdir(parents=True, exist_ok=True)
    L = ["<!-- auto-generated by scripts/eda.py; do not edit by hand -->",
         "# FAR-Trans exploratory analysis (Session 1)", "",
         f"Buy transactions: **{len(b)}** of {len(tx)} rows; data end date {end.date()}. "
         "Counts below are over Buy rows unless stated otherwise.", ""]

    # 1. volume over time
    b["month"] = b.timestamp.dt.to_period("M")
    m = b.pivot_table(index="month", columns="cat", values="transactionID", aggfunc="count", fill_value=0)[CATS]
    m["Total"] = m.sum(axis=1)
    m.to_csv(REPORTS_DIR / "tables" / "monthly_buys_by_category.csv")
    y = b.groupby([b.timestamp.dt.year, "cat"]).size().unstack(fill_value=0)[CATS]
    y["Total"] = y.sum(axis=1)
    jan = b[b.month == pd.Period("2018-01")]
    first_day = int((jan.timestamp == jan.timestamp.min()).sum())
    L += ["## 1. Volume over time", "", "| Year | Stock | MTF | Bond | Total |", "|---|---:|---:|---:|---:|"]
    L += [f"| {yr} | " + " | ".join(str(int(v)) for v in r.values) + " |" for yr, r in y.iterrows()]
    L += ["", f"Monthly counts: `tables/monthly_buys_by_category.csv`. January 2018 has {int(m.loc['2018-01', 'Total'])} Buys "
          f"(the largest month; the median month has {int(m.Total.median())}); {first_day} of them are dated "
          f"{jan.timestamp.min().date()}, the first day with transactions.", "",
          "![monthly buys](figures/monthly_buys_by_category.png)", ""]
    ax = m[CATS].plot(figsize=(9, 3.5), logy=True)
    ax.set_xlabel("month"); ax.set_ylabel("Buy transactions (log)"); ax.set_title("Monthly Buy transactions by asset category (zero months not drawn)")
    ax.legend(title="assetCategory")
    plt.tight_layout(); plt.savefig(FIG_DIR / "monthly_buys_by_category.png", dpi=150); plt.close()

    # 2. per-user activity
    per_user = b.groupby("customerID").size()
    per_user_isin = b.groupby("customerID").ISIN.nunique()
    q = [0.5, 0.75, 0.9, 0.99]
    L += ["## 2. Activity per user", "",
          f"Users with at least one Buy: **{len(per_user)}**.", "",
          "| | p50 | p75 | p90 | p99 | max |", "|---|---:|---:|---:|---:|---:|",
          "| Buys per user | " + " | ".join(str(int(per_user.quantile(x))) for x in q) + f" | {per_user.max()} |",
          "| Distinct ISIN per user | " + " | ".join(str(int(per_user_isin.quantile(x))) for x in q) + f" | {per_user_isin.max()} |",
          "", f"- Buys per user: {buckets(per_user)}.", f"- Distinct ISIN per user: {buckets(per_user_isin)}.", "",
          "![buys per user](figures/buys_per_user.png)", ""]
    fig, axs = plt.subplots(1, 2, figsize=(9, 3.2))
    for a, s, t in [(axs[0], per_user, "Buys per user"), (axs[1], per_user_isin, "Distinct ISIN per user")]:
        vc = s.value_counts().sort_index()
        a.loglog(vc.index, vc.values, ".", ms=4); a.set_xlabel(t); a.set_ylabel("users")
    plt.tight_layout(); plt.savefig(FIG_DIR / "buys_per_user.png", dpi=150); plt.close()

    # 3. repeats
    b["repeat"] = b.duplicated(["customerID", "ISIN"])
    L += ["## 3. Repeat purchases", "",
          "A Buy is a *repeat* if the same user bought the same ISIN on an earlier row "
          "(same-day rows ordered by transactionID).", "",
          "| Category | Buys | Repeat share | Distinct (user, ISIN) pairs |", "|---|---:|---:|---:|"]
    for c in CATS + ["All"]:
        s = b if c == "All" else b[b.cat == c]
        L.append(f"| {c} | {len(s)} | {pct(s.repeat.mean())} | {len(s.drop_duplicates(['customerID', 'ISIN']))} |")
    L.append("")

    # 4. popularity
    pop = b.ISIN.value_counts()
    L += ["## 4. Popularity concentration", "",
          f"Distinct ISIN bought at least once: **{len(pop)}** (of {read_raw('asset_information.csv').ISIN.nunique()} in asset_information).", "",
          "| Category | Distinct ISIN bought | Top-10 share | Top-50 share |", "|---|---:|---:|---:|"]
    for c in CATS + ["All"]:
        p = pop if c == "All" else b[b.cat == c].ISIN.value_counts()
        L.append(f"| {c} | {len(p)} | {pct(p.head(10).sum() / p.sum())} | {pct(p.head(50).sum() / p.sum())} |")
    L.append("")

    # 5. provisional cuts
    cu = load_customers()
    shared = tx.transactionID.duplicated(keep=False)
    shared_ids = set(tx.transactionID[shared])
    cp = read_raw("close_prices.csv")
    cp_first = pd.to_datetime(cp.groupby("ISIN").timestamp.min())
    L += ["## 5. Provisional cut scenarios", "",
          "> ⚠️ **NOT THE OFFICIAL SPLIT.** The official cut, item scope and evaluated users are pending. "
          "These cuts are exploratory, only to size a feasible evaluation.", "",
          "Definitions: history = Buys with date `< T`; test window = `[T, data end]`; "
          "*evaluated user* = ≥1 Buy before `T` and ≥1 Buy in the test window; "
          "*target set* = distinct ISINs a user buys in the test window (the relevant items for nDCG@10); "
          "*target pairs* = (user, ISIN) pairs over all evaluated users; all scope = all asset categories.", ""]
    hdr = ["Cut T", "Eval users", "Target pairs", "Mean targets/user", "Pairs already bought by user before T",
           "Pairs in pre-T top-10 popular", "Users with ≥1 target in pre-T top-10", "Target ISINs never bought before T (pairs)",
           "Users with only new-to-user targets", "Users with no snapshot available before T", "Pairs via shared transactionID",
           "Eval users by pre-T Buys: 1 / 2–4 / 5+", "Users with Buys only in test window", "Assets with a price before T"]
    rows = []
    for T in CUTS:
        t = pd.Timestamp(T)
        hist, fut = b[b.timestamp < t], b[b.timestamp >= t]
        users = sorted(set(hist.customerID) & set(fut.customerID))
        tgt = fut[fut.customerID.isin(users)].drop_duplicates(["customerID", "ISIN"])
        hp = set(zip(hist.customerID, hist.ISIN))
        known = pd.Series([p in hp for p in zip(tgt.customerID, tgt.ISIN)], index=tgt.index)
        top10 = set(hist.ISIN.value_counts().head(10).index)
        in_top = tgt.ISIN.isin(top10)
        cold_item = ~tgt.ISIN.isin(set(hist.ISIN))
        only_new = (~known).groupby(tgt.customerID).all()
        avail = cu[cu.timestamp.notna() & (cu.available_from < t)].customerID
        no_prof = len(set(users) - set(avail))
        via_shared = fut[fut.customerID.isin(users) & fut.transactionID.isin(shared_ids)].drop_duplicates(["customerID", "ISIN"])
        hn = hist[hist.customerID.isin(users)].groupby("customerID").size()
        rows.append([
            T, len(users), len(tgt), f"{len(tgt) / len(users):.2f}", pct(known.mean()), pct(in_top.mean()),
            pct(in_top.groupby(tgt.customerID).any().mean()), f"{int(cold_item.sum())} ({pct(cold_item.mean())})",
            f"{int(only_new.sum())} ({pct(only_new.mean())})", f"{no_prof} ({pct(no_prof / len(users))})",
            f"{len(via_shared)} ({pct(len(via_shared) / len(tgt))})",
            f"{int((hn == 1).sum())} / {int(hn.between(2, 4).sum())} / {int((hn >= 5).sum())}",
            len(set(fut.customerID) - set(hist.customerID)), int((cp_first < t).sum()),
        ])
    tab = pd.DataFrame(rows, columns=hdr).set_index("Cut T").T
    L += ["| Measure | " + " | ".join(CUTS) + " |", "|---|" + "---:|" * len(CUTS)]
    L += [f"| {k} | " + " | ".join(str(v) for v in r.values) + " |" for k, r in tab.iterrows()]

    # facts
    r0 = dict(zip(hdr, rows[0]))
    L += ["", "## 6. Observations (facts from the tables above; no modelling claims)", "",
          f"- Stocks account for {pct((b.cat == 'Stock').mean())} of Buys; MTF {pct((b.cat == 'MTF').mean())}; "
          f"Bond {pct((b.cat == 'Bond').mean())} (§1).",
          f"- {pct((per_user == 1).mean())} of users have exactly one Buy; the top 1% of users have at least "
          f"{int(per_user.quantile(0.99))} Buys (§2).",
          f"- {pct(b.repeat.mean())} of all Buys repeat an ISIN the user already bought; for Stock "
          f"{pct(b[b.cat == 'Stock'].repeat.mean())}, for MTF {pct(b[b.cat == 'MTF'].repeat.mean())}, "
          f"for Bond {pct(b[b.cat == 'Bond'].repeat.mean())} (§3).",
          f"- The 10 most bought ISINs cover {pct(pop.head(10).sum() / pop.sum())} of Buys (§4).",
          f"- At the provisional cut {CUTS[0]}: {r0['Eval users']} evaluated users; "
          f"{r0['Pairs already bought by user before T']} of target pairs were already bought by the same user before T, "
          f"and {r0['Pairs in pre-T top-10 popular']} are in the pre-T top-10 (§5).",
          "- Whether repeat purchases count as relevant items is not yet fixed by the protocol; the share above "
          "shows that this choice changes the task substantially.", ""]
    (REPORTS_DIR / "eda.md").write_text("\n".join(L), encoding="utf-8")
    print("ok: reports/session1/eda.md")


if __name__ == "__main__":
    main()
